import pandas as pd
from pathlib import Path

# Subsystem 1 imports (Ecesu's pipeline & database)
from subsystem1.database import DatabaseManager
from subsystem1.feature_engineering import DEFAULT_BUILDING_CATALOG
from subsystem1.metrics import MetricsCalculator

# Subsystem 2 imports (Stella's AI training & prediction)
from subsystem2.Data_processor import Dataprocessor
from subsystem2.Energy_predictor import ModelTrainer
from subsystem2.AI_prediction import AIPrediction
from subsystem2.Model_evaluation import ModelEvaluator
from subsystem2.Prediction_result import predict_all

# Subsystem 3 imports (Your optimization engine & visualizer)
from subsystem3.optimizer import OptimisationEngine
from subsystem3.visualizer import ResultsVisualiser


def main():
    print("=" * 70)
    print("AI-POWERED SMART ENERGY MANAGEMENT SYSTEM - SYSTEM INTEGRATION")
    print("=" * 70)

    # Step 1: Load processed data generated by Ecesu's Subsystem 1
    data_path = Path("data/processed/enriched_energy_data.csv")
    if not data_path.exists():
        print(f"[-] Error: {data_path} not found. Please run Ecesu's pipeline first!")
        return

    print("[+] Loading engineered energy dataset...")
    df = pd.read_csv(data_path)

    # Step 2: Train Stella's AI models (Subsystem 2)
    print("[+] Initializing and training AI prediction models...")
    prep = Dataprocessor(df, target="EnergyConsumption")
    X_train, X_test, y_train, y_test = prep.process(test_size=0.2)

    trainer = ModelTrainer()
    trained_models = trainer.train(X_train, y_train)

    # Evaluate models to find the best one
    results = predict_all(trained_models, X_test, y_test)
    evaluator = ModelEvaluator()
    table = evaluator.compare(results)
    best_model_name = table.iloc[0]["model"]
    print(f"[+] Best Performing AI Model Selected: {best_model_name}")

    # Package into AIPrediction engine
    ai_predictor = AIPrediction(prep, trained_models, best_model_name)

    # Step 3: Run Your Subsystem 3 Optimisation Engine
    print("[+] Running Subsystem 3 Optimisation Engine...")
    metrics_calc = MetricsCalculator()
    optimizer = OptimisationEngine(ai_predictor=ai_predictor, metrics_calculator=metrics_calc)
    
    # Generate scenarios and evaluate them
    scenarios = optimizer.generate_scenarios()
    evaluation_results = [optimizer.evaluate_scenario(s) for s in scenarios]
    best_scenario = optimizer.select_best_scenario(evaluation_results)

    print("\n" + "-" * 70)
    print("OPTIMISATION RESULTS SUMMARY:")
    print("-" * 70)
    for i, res in enumerate(evaluation_results):
        status = "★ RECOMMENDED BEST" if res.recommended else "Tested Scenario"
        print(f"Scenario {i+1} ({status}):")
        print(f"  - Energy Consumption : {res.energy_kwh:,.2f} kWh")
        print(f"  - Operational Cost   : EUR {res.cost_eur:,.2f}")
        print(f"  - Carbon Footprint   : {res.carbon_kg:,.2f} kg CO2")
        print(f"  - Efficiency Score   : {res.score} / 100")
    print("-" * 70)

    # Step 4: Display Visualisations (Subsystem 3 Visualiser)
    print("[+] Generating dashboard comparison charts...")
    visualiser = ResultsVisualiser()
    
    # This will render and pop up the Matplotlib chart windows
    visualiser.plot_energy_comparison(evaluation_results)
    visualiser.plot_cost_comparison(evaluation_results)
    visualiser.plot_carbon_comparison(evaluation_results)

    print("\n[+] System pipeline and Subsystem 3 integration executed successfully!")


if __name__ == "__main__":
    main()